export function buildWord(t: WordTuple, tier: 1 | 2 | 3): Word {
  const [spelling, phonetic, pos, meanings, example] = t;
  const [en, zh] = example.split('||');
  return {
    id: spelling,
    spelling,
    phonetic: phonetic ?? undefined,
    pos,
    meanings: meanings.split(';'),
    examples: [{ en: en.trim(), zh: (zh ?? '').trim() }],
    tier,
  };
}

export const tier1Words: Word[] = tier1Raw.map(t => buildWord(t, 1));
